local function cave(key)
  if S.caves[key] then return S.caves[key] end
  local profile=DATA.profiles[key]
  local address=assert(allocateMemory(0x20000,base),'코드 메모리 할당 실패')
  assert(address~=0,'코드 메모리 할당 실패')
