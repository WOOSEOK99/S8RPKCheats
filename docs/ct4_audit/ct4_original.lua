  if enabled and feature.dependency then assert(S.active[feature.dependency],'먼저 공격 대상 확대를 켜 주세요.') end
  if not enabled then for k,f in pairs(DATA.features) do assert(not(S.active[k] and f.dependency==key),'의존 옵션을 먼저 꺼 주세요: '..f.name) end end
  local writes={};local ranges={}
  if enabled then
    validate(profile)
    local c=cave(feature.profile)
    for _,idx in ipairs(feature.hooks) do
      local h=profile.hooks[idx];local before=hx(h.original)
      local br=h.rva==0x17B0BA0 and bridge() or nil
      if br then
        writes[#writes+1]={address=br.slot,before=pack(br.trampoline),after=pack(c+h.offset)}
      else
        local after
        if h.call then
          local displacement=c+h.offset-(base+h.rva+5)
          assert(displacement>=-0x80000000 and displacement<=0x7FFFFFFF,'근거리 코드 할당 실패')
          after={0xE8,string.pack('<i4',displacement):byte(1,4)}
        else after=h.offset<0 and hx(h.patch) or jump(c+h.offset,#before) end
        writes[#writes+1]={address=base+h.rva,before=before,after=after,gameRva=h.rva}
        ranges[#ranges+1]={base+h.rva,#before}
      end
    end
  else
    for _,w in ipairs(S.active[key].writes) do
      writes[#writes+1]={address=w.address,before=w.after,after=w.before,gameRva=w.gameRva}
      if w.gameRva then ranges[#ranges+1]={w.address,#w.before} end
    end
  end
  frozen(ranges,function()
    if enabled then validate(profile) end
    for _,w in ipairs(writes) do assert(same(read(w.address,#w.before),w.before),string.format('수정 전 코드 불일치: %X',w.address)) end
    local attempted={}
    local ok,err=pcall(function() for _,w in ipairs(writes) do attempted[#attempted+1]=w;write(w.address,w.after) end end)
    if not ok then
      local errors={}
      for i=#attempted,1,-1 do local w=attempted[i];local good,msg=pcall(write,w.address,w.before);if not good then errors[#errors+1]=tostring(msg) end end
      if #errors>0 then S.recovery=attempted;error('부분 변경 복구 실패. 게임을 재시작해 주세요. '..table.concat(errors,'\n')) end
      error(err)
    end
    S.active[key]=enabled and {writes=writes} or nil
  end)
end
