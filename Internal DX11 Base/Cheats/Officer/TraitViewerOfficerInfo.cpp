bool BuildCave(uintptr_t b) {
  g_cave = AllocNear(b + 0x1CC3003, 0x10000);
  if (!g_cave)
    return false;

  const uint64_t zero = 0;
  if (!WriteMemory(g_cave, &zero, 8))
    return false;

  // owner vtable: first slot native, destructor replaced, remaining 0x240 bytes native.
  if (!WriteMemory(g_cave + 0x100, reinterpret_cast<const void *>(b + 0x26F92C0), 8))
    return false;
  const uint64_t destroyPtr = g_cave + 0x1800;
  if (!WriteMemory(g_cave + 0x108, &destroyPtr, 8))
    return false;
  if (!WriteMemory(g_cave + 0x110, reinterpret_cast<const void *>(b + 0x26F92D0), 0x240))
    return false;

  // Rects/IDs copied exactly as the CT.
  if (!WriteMemory(g_cave + 0x400, reinterpret_cast<const void *>(b + 0x2C13A90), 0x10) ||
      !WriteMemory(g_cave + 0x410, reinterpret_cast<const void *>(b + 0x2C13AB0), 0x10))
    return false;
  const uint32_t rectTail[] = {0x4E4,0x35C,0x8C,0x24};
  const uint32_t ids[] = {6,8,9};
  if (!WriteMemory(g_cave + 0x420, rectTail, sizeof(rectTail)) ||
      !WriteMemory(g_cave + 0x450, ids, sizeof(ids)))
    return false;

  auto install = [&](uintptr_t off, const uint8_t *src, size_t n,
                     std::initializer_list<std::pair<size_t, uintptr_t>> relocs) {
    std::vector<uint8_t> v(src, src+n);
    for (const auto &r : relocs) {
      if (!PutRel32(v, r.first, g_cave + off, r.second))
        return false;
    }
    return WriteMemory(g_cave + off, v.data(), v.size());
  };

  if (!install(0x1000,kFinish,sizeof(kFinish),{{0x25,b+0x1D000B4}}) ||
      !install(0x1100,kGroup,sizeof(kGroup),{{0x0D,b+0x1D13E60},{0xB6,b+0x1D13E60}}) ||
      !install(0x1400,kLoop,sizeof(kLoop),{{0x2F,b+0x1CC300F}}) ||
      !install(0x1500,kDisplay,sizeof(kDisplay),{{0x15,b+0x1CC2370},{0x1A,b+0x1CC256D},{0x24,b+0x1CC2370},{0x29,b+0x1CC256D}}) ||
      !install(0x1600,kHide,sizeof(kHide),{{0x15,b+0x1CC25B4},{0x1A,b+0x1CC2573},{0x24,b+0x1CC25B4},{0x29,b+0x1CC2573}}) ||
      !install(0x1700,kHideCount,sizeof(kHideCount),{{0x1A,b+0x1CC2586}}) ||
      !install(0x1800,kDestroy,sizeof(kDestroy),{{0x0B,b+0x6AFA70}}))
    return false;
  return true;
}

bool Apply(uintptr_t b) {
  if (!VerifyVersion(b)) {
    AddLog(u8"[기재 화면/정보창] 91513 원본 바이트 검증 실패. 적용하지 않습니다.");
    return false;
  }
  if (!BuildCave(b))
    return false;

  static constexpr uint8_t kSizeNew[] = {0xBA,0xE0,0x01,0x00,0x00};
  if (!WriteMemory(b + 0x1D00092, kSizeNew, sizeof(kSizeNew)) ||
      !WriteBranch(b + 0x1D000AC, g_cave + 0x1000, 0xE9, 5) ||
      !WriteBranch(b + 0x1CC2D84, g_cave + 0x1100, 0xE8, 5) ||
      !WriteBranch(b + 0x1CC3003, g_cave + 0x1400, 0xE9, 12) ||
      !WriteBranch(b + 0x1CC2563, g_cave + 0x1500, 0xE9, 10) ||
      !WriteBranch(b + 0x1CC256D, g_cave + 0x1600, 0xE9, 6) ||
      !WriteBranch(b + 0x1CC2581, g_cave + 0x1700, 0xE9, 5))
    return false;
  return true;
}

void Restore() {
  if (!g_base)
    return;
  WriteMemory(g_base + 0x1CC2581, kHideCountOrig, sizeof(kHideCountOrig));
  WriteMemory(g_base + 0x1CC256D, kHideOrig, sizeof(kHideOrig));
  WriteMemory(g_base + 0x1CC2563, kDisplayOrig, sizeof(kDisplayOrig));
  WriteMemory(g_base + 0x1CC3003, kLoopOrig, sizeof(kLoopOrig));
  WriteMemory(g_base + 0x1CC2D84, kGroupOrig, sizeof(kGroupOrig));
  WriteMemory(g_base + 0x1D000AC, kFinishOrig, sizeof(kFinishOrig));
  WriteMemory(g_base + 0x1D00092, kSizeOrig, sizeof(kSizeOrig));
  if (g_cave) {
    VirtualFree(reinterpret_cast<void *>(g_cave), 0, MEM_RELEASE);
    g_cave = 0;
  }
}

