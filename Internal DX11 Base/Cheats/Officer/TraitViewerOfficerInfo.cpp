bool VerifyVersion(uintptr_t b) {
  return MatchRaw(b + 0x1CFBCF0, kGuardCtor, sizeof(kGuardCtor)) &&
         MatchRaw(b + 0x1CC2D76, kGuardCountA, sizeof(kGuardCountA)) &&
         MatchRaw(b + 0x1CC2FC6, kGuardCountB, sizeof(kGuardCountB)) &&
         MatchRaw(b + 0x1D00092, kSizeOrig, sizeof(kSizeOrig)) &&
         MatchRaw(b + 0x1D000AC, kFinishOrig, sizeof(kFinishOrig)) &&
         MatchRaw(b + 0x1CC2D84, kGroupOrig, sizeof(kGroupOrig)) &&
         MatchRaw(b + 0x1CC3003, kLoopOrig, sizeof(kLoopOrig)) &&
         MatchRaw(b + 0x1CC2563, kDisplayOrig, sizeof(kDisplayOrig)) &&
         MatchRaw(b + 0x1CC256D, kHideOrig, sizeof(kHideOrig)) &&
         MatchRaw(b + 0x1CC2581, kHideCountOrig, sizeof(kHideCountOrig));
}

