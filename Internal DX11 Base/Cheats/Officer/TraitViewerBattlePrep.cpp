struct Reloc {
  size_t offset;
  uintptr_t targetOffset;
};

bool InstallCode(uintptr_t caveOffset, const uint8_t *bytes, size_t size,
                 const Reloc *relocs, size_t relocCount, uintptr_t base) {
  std::vector<uint8_t> code(bytes, bytes + size);
  for (size_t i = 0; i < relocCount; ++i) {
    if (relocs[i].offset < caveOffset || relocs[i].offset + 4 > caveOffset + size)
      return false;
    if (!PutRel32(code, relocs[i].offset - caveOffset, g_cave + caveOffset, base + relocs[i].targetOffset))
      return false;
  }
  return WriteMemory(g_cave + caveOffset, code.data(), code.size());
}

bool BuildCave(uintptr_t b) {
  g_cave = AllocNear(b + 0x1A1B52C, 0x10000);
  if (!g_cave)
    return false;

  // Extra trait button vtable. CE points objects at +0x808 (custom destructor first).
  if (!WriteMemory(g_cave + 0x800, reinterpret_cast<const void *>(b + 0x25EE268), 8))
    return false;
  const uint64_t buttonDestroy = g_cave + 0x2400;
  if (!WriteMemory(g_cave + 0x808, &buttonDestroy, 8) ||
      !WriteMemory(g_cave + 0x810, reinterpret_cast<const void *>(b + 0x25EE278), 0x260))
    return false;

  const uint32_t dx[] = {0x00000000, 0x431E0000, 0x439E0000};
  const uint32_t dy[] = {0xC1000000, 0x41F00000, 0x42880000};
  if (!WriteMemory(g_cave + 0xB00, dx, sizeof(dx)) ||
      !WriteMemory(g_cave + 0xB10, dy, sizeof(dy)))
    return false;

  // Battle-preparation owner vtable. Keep native entries except the five hooks from the CT.
  if (!WriteMemory(g_cave + 0x3000, reinterpret_cast<const void *>(b + 0x26B0808), 8))
    return false;
  const uint64_t ownerDestroy = g_cave + 0x4800;
  const uint64_t ownerUpdate = g_cave + 0x4000;
  const uint64_t ownerRender = g_cave + 0x4400;
  const uint64_t ownerAttach = g_cave + 0x5400;
  const uint64_t ownerDetach = g_cave + 0x5800;
  if (!WriteMemory(g_cave + 0x3008, &ownerDestroy, 8) ||
      !WriteMemory(g_cave + 0x3010, reinterpret_cast<const void *>(b + 0x26B0818), 0x18) ||
      !WriteMemory(g_cave + 0x3028, &ownerUpdate, 8) ||
      !WriteMemory(g_cave + 0x3030, &ownerRender, 8) ||
      !WriteMemory(g_cave + 0x3038, reinterpret_cast<const void *>(b + 0x26B0840), 0x18) ||
      !WriteMemory(g_cave + 0x3050, &ownerAttach, 8) ||
      !WriteMemory(g_cave + 0x3058, &ownerDetach, 8) ||
      !WriteMemory(g_cave + 0x3060, reinterpret_cast<const void *>(b + 0x26B0868), 0x3A8))
    return false;

  static constexpr Reloc hookRelocs[] = {{0x10A6, 0x1A1B533}};
  static constexpr Reloc updateRelocs[] = {
      {0x148E,0x14ED0}, {0x14CB,0x162ECA0}, {0x1519,0x161AF00},
      {0x1536,0x1EF5F40}, {0x15F6,0x162EDA0}, {0x1602,0x2E99C98},
      {0x1617,0x16AC280}, {0x162F,0x162EEC0},
  };
  static constexpr Reloc destroyRelocs[] = {{0x2470,0x1725E0}};
  static constexpr Reloc ownerUpdateRelocs[] = {{0x401A,0x19EEA70}};
  static constexpr Reloc ownerRenderRelocs[] = {{0x441A,0x1EDEF10}};
  static constexpr Reloc ownerDestroyRelocs[] = {{0x486B,0x619030}};
  static constexpr Reloc hoverRelocs[] = {{0x506A,0x170ABB0}, {0x50A3,0x19ED9F6}};
  static constexpr Reloc ownerAttachRelocs[] = {{0x541A,0x19EEB10}};
  static constexpr Reloc ownerDetachRelocs[] = {{0x581A,0x19EEAB0}};
  static constexpr Reloc tooltipRelocs[] = {{0x5CA6,0x1A18B46}};

  return InstallCode(0x1000,kHookCode,sizeof(kHookCode),hookRelocs,std::size(hookRelocs),b) &&
         InstallCode(0x1400,kUpdateCode,sizeof(kUpdateCode),updateRelocs,std::size(updateRelocs),b) &&
         InstallCode(0x2400,kDestroyCode,sizeof(kDestroyCode),destroyRelocs,std::size(destroyRelocs),b) &&
         InstallCode(0x4000,kOwnerUpdateCode,sizeof(kOwnerUpdateCode),ownerUpdateRelocs,std::size(ownerUpdateRelocs),b) &&
         InstallCode(0x4400,kOwnerRenderCode,sizeof(kOwnerRenderCode),ownerRenderRelocs,std::size(ownerRenderRelocs),b) &&
         InstallCode(0x4800,kOwnerDestroyCode,sizeof(kOwnerDestroyCode),ownerDestroyRelocs,std::size(ownerDestroyRelocs),b) &&
         InstallCode(0x5000,kHoverCode,sizeof(kHoverCode),hoverRelocs,std::size(hoverRelocs),b) &&
         InstallCode(0x5400,kOwnerAttachCode,sizeof(kOwnerAttachCode),ownerAttachRelocs,std::size(ownerAttachRelocs),b) &&
         InstallCode(0x5800,kOwnerDetachCode,sizeof(kOwnerDetachCode),ownerDetachRelocs,std::size(ownerDetachRelocs),b) &&
         InstallCode(0x5C00,kTooltipCode,sizeof(kTooltipCode),tooltipRelocs,std::size(tooltipRelocs),b);
}

bool Apply(uintptr_t b) {
  if (!VerifyVersion(b)) {
    AddLog(u8"[기재 화면/전투준비] 91503 원본 바이트 검증 실패. 적용하지 않습니다.");
    return false;
  }
  if (!BuildCave(b)) {
    AddLog(u8"[기재 화면/전투준비] 91503 코드 영역 생성 실패.");
    return false;
  }

  if (!WriteBranch(b + 0x1A1B52C, g_cave + 0x1000, 7))
    return false;
  if (!WriteBranch(b + 0x19ED9F0, g_cave + 0x5000, 6)) {
    WriteMemory(b + 0x1A1B52C, kHookOrig, sizeof(kHookOrig));
    return false;
  }
  if (!WriteBranch(b + 0x1A18B41, g_cave + 0x5C00, 5)) {
    WriteMemory(b + 0x19ED9F0, kHoverOrig, sizeof(kHoverOrig));
    WriteMemory(b + 0x1A1B52C, kHookOrig, sizeof(kHookOrig));
    return false;
  }
  return true;
}

void Restore() {
  if (!g_base)
    return;
  WriteMemory(g_base + 0x1A18B41, kTooltipOrig, sizeof(kTooltipOrig));
  WriteMemory(g_base + 0x19ED9F0, kHoverOrig, sizeof(kHoverOrig));
  WriteMemory(g_base + 0x1A1B52C, kHookOrig, sizeof(kHookOrig));
  if (g_cave) {
    VirtualFree(reinterpret_cast<void *>(g_cave), 0, MEM_RELEASE);
    g_cave = 0;
  }
}

