bool MatchRaw(uintptr_t address, const uint8_t *expected, size_t size) {
  return std::memcmp(reinterpret_cast<const void *>(address), expected, size) == 0;
}

bool WriteMemory(uintptr_t address, const void *data, size_t size) {
  DWORD oldProtect = 0;
  if (!VirtualProtect(reinterpret_cast<void *>(address), size, PAGE_EXECUTE_READWRITE, &oldProtect))
    return false;
  std::memcpy(reinterpret_cast<void *>(address), data, size);
  FlushInstructionCache(GetCurrentProcess(), reinterpret_cast<void *>(address), size);
  DWORD ignored = 0;
  VirtualProtect(reinterpret_cast<void *>(address), size, oldProtect, &ignored);
  return true;
}

bool PutRel32(std::vector<uint8_t> &code, size_t dispOffset, uintptr_t codeAddress, uintptr_t target) {
  const int64_t delta = static_cast<int64_t>(target) - static_cast<int64_t>(codeAddress + dispOffset + 4);
  if (delta < INT32_MIN || delta > INT32_MAX)
    return false;
  const int32_t rel = static_cast<int32_t>(delta);
  std::memcpy(code.data() + dispOffset, &rel, sizeof(rel));
  return true;
}

bool WriteBranch(uintptr_t from, uintptr_t to, size_t totalSize) {
  if (totalSize < 5)
    return false;
  const int64_t delta = static_cast<int64_t>(to) - static_cast<int64_t>(from + 5);
  if (delta < INT32_MIN || delta > INT32_MAX)
    return false;
  std::vector<uint8_t> patch(totalSize, 0x90);
  patch[0] = 0xE9;
  const int32_t rel = static_cast<int32_t>(delta);
  std::memcpy(patch.data() + 1, &rel, sizeof(rel));
  return WriteMemory(from, patch.data(), patch.size());
}

