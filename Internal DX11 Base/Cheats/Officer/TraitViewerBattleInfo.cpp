bool SetTraitViewerBattleInfo(bool enable) {
  if (enable == g_applied)
    return true;
  if (!enable) {
    if (g_cave && *reinterpret_cast<volatile uint64_t *>(g_cave) != 0) {
      AddLog(u8"[기재 화면/전투정보] 부대 정보 객체가 남아 있어 해제할 수 없습니다. 전투 화면을 닫고 다시 시도하세요.");
      return false;
    }
    Restore();
    g_applied=false;
    AddLog(u8"[기재 화면/전투정보] 세 번째 기재/설명 패치 해제");
    return true;
  }
  HMODULE mod=GetModuleHandleW(L"SAN8RPK.exe");
  if (!mod)
    return false;
  g_base=reinterpret_cast<uintptr_t>(mod);
  if (!Apply(g_base)) {
    if (g_cave && *reinterpret_cast<volatile uint64_t *>(g_cave)==0)
      Restore();
    g_base=0;
    return false;
  }
  g_applied=true;
  AddLog(u8"[기재 화면/전투정보] 세 번째 기재/설명 패치 적용");
  return true;
}

