bool MatchRaw(uintptr_t a, const uint8_t *p, size_t n) {
  return std::memcmp(reinterpret_cast<const void *>(a), p, n) == 0;
}

bool WriteMemory(uintptr_t a, const void *p, size_t n) {
  DWORD oldProtect = 0;
  if (!VirtualProtect(reinterpret_cast<void *>(a), n, PAGE_EXECUTE_READWRITE, &oldProtect))
    return false;
  std::memcpy(reinterpret_cast<void *>(a), p, n);
  FlushInstructionCache(GetCurrentProcess(), reinterpret_cast<void *>(a), n);
  DWORD ignored = 0;
  VirtualProtect(reinterpret_cast<void *>(a), n, oldProtect, &ignored);
  return true;
}

bool PutRel32(std::vector<uint8_t> &v, size_t disp, uintptr_t code, uintptr_t target) {
  const int64_t d = static_cast<int64_t>(target) - static_cast<int64_t>(code + disp + 4);
  if (d < std::numeric_limits<int32_t>::min() || d > std::numeric_limits<int32_t>::max())
    return false;
  const int32_t r = static_cast<int32_t>(d);
  std::memcpy(v.data() + disp, &r, 4);
  return true;
}

bool Install(uintptr_t off, const uint8_t *src, size_t n,
             std::initializer_list<std::pair<size_t, uintptr_t>> relocs) {
  std::vector<uint8_t> v(src, src + n);
  for (auto &r : relocs)
    if (!PutRel32(v, r.first, g_cave + off, r.second))
      return false;
  return WriteMemory(g_cave + off, v.data(), v.size());
}

bool WriteBranch(uintptr_t from, uintptr_t to, uint8_t opcode, size_t n) {
  if (n < 5)
    return false;
  const int64_t d = static_cast<int64_t>(to) - static_cast<int64_t>(from + 5);
  if (d < std::numeric_limits<int32_t>::min() || d > std::numeric_limits<int32_t>::max())
    return false;
  std::vector<uint8_t> v(n, 0x90);
  v[0] = opcode;
  const int32_t r = static_cast<int32_t>(d);
  std::memcpy(v.data()+1,&r,4);
  return WriteMemory(from,v.data(),v.size());
}

