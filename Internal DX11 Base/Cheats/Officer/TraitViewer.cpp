template <size_t N>
bool Match(uintptr_t address, const std::array<uint8_t, N> &expected) {
  return std::memcmp(reinterpret_cast<const void *>(address), expected.data(), N) == 0;
}

bool MatchRaw(uintptr_t address, const uint8_t *expected, size_t size) {
  return std::memcmp(reinterpret_cast<const void *>(address), expected, size) == 0;
}

bool WriteMemory(uintptr_t address, const void *data, size_t size) {
  DWORD oldProtect = 0;
  if (!VirtualProtect(reinterpret_cast<void *>(address), size, PAGE_EXECUTE_READWRITE, &oldProtect))
    return false;
  std::memcpy(reinterpret_cast<void *>(address), data, size);
  FlushInstructionCache(GetCurrentProcess(), reinterpret_cast<void *>(address), size);
  DWORD ignored = 0;
  VirtualProtect(reinterpret_cast<void *>(address), size, oldProtect, &ignored);
  return true;
}

template <typename T>
bool WriteValue(uintptr_t address, T value) {
  return WriteMemory(address, &value, sizeof(value));
}

bool PutRel32(std::vector<uint8_t> &code, size_t dispOffset, uintptr_t codeAddress, uintptr_t target) {
  const uintptr_t next = codeAddress + dispOffset + 4;
  const int64_t delta = static_cast<int64_t>(target) - static_cast<int64_t>(next);
  if (delta < std::numeric_limits<int32_t>::min() || delta > std::numeric_limits<int32_t>::max())
    return false;
  const int32_t rel = static_cast<int32_t>(delta);
  std::memcpy(code.data() + dispOffset, &rel, sizeof(rel));
  return true;
}

bool VerifyRosterVersion(uintptr_t base) {
  static constexpr std::array<uint8_t, 56> kAbilityColumns = {
      0x00,0x00,0x00,0x00, 0x05,0x00,0x00,0x00, 0x07,0x00,0x00,0x00, 0xA4,0x00,0x00,0x00,
      0x18,0x00,0x00,0x00, 0x19,0x00,0x00,0x00, 0x1A,0x00,0x00,0x00, 0x1B,0x00,0x00,0x00,
      0x1C,0x00,0x00,0x00, 0xAB,0x00,0x00,0x00, 0xE6,0x00,0x00,0x00, 0x73,0x00,0x00,0x00,
      0x74,0x00,0x00,0x00, 0xFF,0xFF,0xFF,0xFF
  };
  static constexpr std::array<uint8_t, 8> kThirdColumnId = {0x75,0,0,0,0,0,0,0};
  static constexpr std::array<uint8_t, 8> kThirdColumnMeta = {0x92,0,0,0,1,0,0,0};
  static constexpr std::array<uint8_t, 8> kThirdColumnEnd = {0xFF,0xFF,0,0,1,0,0,0};
  static constexpr std::array<uint8_t, 5> kGetNamePrologue = {0x48,0x89,0x5C,0x24,0x08};

  if (*reinterpret_cast<uintptr_t *>(base + kRosterColumnListPtr) != base + kRosterColumnList)
    return false;
  if (*reinterpret_cast<uintptr_t *>(base + kThirdFormatPtr) != base + kOriginalFormat ||
      *reinterpret_cast<uintptr_t *>(base + kThirdSortPtr) != base + kOriginalSort)
    return false;
  return Match(base + 0x3A6C0F0, kAbilityColumns) &&
         Match(base + 0x2C71CE8, kThirdColumnId) &&
         Match(base + 0x2C71CF8, kThirdColumnMeta) &&
         Match(base + 0x2C71D30, kThirdColumnEnd) &&
         Match(base + 0x1AE5BA0, kGetNamePrologue);
}

