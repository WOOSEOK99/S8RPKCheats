bool ApplyCorePatches(uintptr_t base) {
  if (!VerifyRosterVersion(base) || !BuildRosterCave(base)) {
    AddLog(u8"[기재 화면] 기재3 열 코드 검증/할당 실패. 게임 버전을 확인하세요.");
    return false;
  }

  g_rosterBackup.cf0 = *reinterpret_cast<uint64_t *>(base + 0x2C71CF0);
  g_rosterBackup.cfc = *reinterpret_cast<uint32_t *>(base + 0x2C71CFC);
  g_rosterBackup.d00 = *reinterpret_cast<uint64_t *>(base + 0x2C71D00);
  g_rosterBackup.d10 = *reinterpret_cast<uint64_t *>(base + 0x2C71D10);
  g_rosterBackup.term = *reinterpret_cast<uint32_t *>(base + 0x3A6C124);
  g_unitWidthOriginal = *reinterpret_cast<uint32_t *>(base + 0x2C72958);
  g_statusWidthOriginal = *reinterpret_cast<uint32_t *>(base + 0x2C6F678);
  g_haveBackups = true;

  static constexpr std::array<uint8_t,8> kUnitId = {0x99,0,0,0,0,0,0,0};
  static constexpr std::array<uint8_t,8> kStatusId = {0x05,0,0,0,0,0,0,0};
  if (!Match(base + 0x2C72948, kUnitId) || g_unitWidthOriginal != 0xBC ||
      !Match(base + 0x2C6F668, kStatusId) || g_statusWidthOriginal != 0x68) {
    AddLog(u8"[기재 화면] 부대/신분 열 너비가 예상값과 달라 적용하지 않습니다.");
    return false;
  }

  for (const auto &p : kListPatches) {
    if (!MatchRaw(base + p.assertOffset, p.assertBytes, p.assertSize)) {
      AddLog(u8"[기재 화면] 선택 목록 테이블 검증 실패: +0x%llX", (unsigned long long)p.assertOffset);
      return false;
    }
  }

  const uint64_t title = g_rosterCave + 0x250;
  const uint64_t fmt = g_rosterCave + 0x000;
  const uint64_t sort = g_rosterCave + 0x100;
  if (!WriteValue(base + 0x2C71CF0, title) ||
      !WriteValue(base + 0x2C71CFC, uint32_t(0x20000001)) ||
      !WriteValue(base + 0x2C71D00, fmt) ||
      !WriteValue(base + 0x2C71D10, sort) ||
      !WriteValue(base + 0x3A6C124, uint32_t(0x75)) ||
      !WriteValue(base + 0x2C72958, uint32_t(0xA0)) ||
      !WriteValue(base + 0x2C6F678, uint32_t(0x4C))) {
    return false;
  }

  g_listBackups.clear();
  for (const auto &p : kListPatches) {
    g_listBackups.push_back({p.terminatorOffset, *reinterpret_cast<uint32_t *>(base + p.terminatorOffset)});
    if (!WriteValue(base + p.terminatorOffset, uint32_t(0x75)))
      return false;
  }
  return true;
}

void RestoreCorePatches() {
  if (!g_base)
    return;

  if (!g_haveBackups) {
    if (g_rosterCave) {
      VirtualFree(reinterpret_cast<void *>(g_rosterCave), 0, MEM_RELEASE);
      g_rosterCave = 0;
    }
    return;
  }

  for (auto it = g_listBackups.rbegin(); it != g_listBackups.rend(); ++it)
    WriteValue(g_base + it->offset, it->value);
  g_listBackups.clear();

  if (g_unitWidthOriginal)
    WriteValue(g_base + 0x2C72958, g_unitWidthOriginal);
  if (g_statusWidthOriginal)
    WriteValue(g_base + 0x2C6F678, g_statusWidthOriginal);

  WriteValue(g_base + 0x3A6C124, g_rosterBackup.term);
  WriteValue(g_base + 0x2C71D10, g_rosterBackup.d10);
  WriteValue(g_base + 0x2C71D00, g_rosterBackup.d00);
  WriteValue(g_base + 0x2C71CFC, g_rosterBackup.cfc);
  WriteValue(g_base + 0x2C71CF0, g_rosterBackup.cf0);

  if (g_rosterCave) {
    VirtualFree(reinterpret_cast<void *>(g_rosterCave), 0, MEM_RELEASE);
    g_rosterCave = 0;
  }
  g_haveBackups = false;
}

